/* Merges resources approved by the AI Deck resource agents (see /agents) into the site data.
   Additive only: agent output can add items, never remove or replace hand-written ones.
   lib/agent-additions.json is generated by `npm run agents -- apply`. Do not edit it by hand. */
import raw from "./agent-additions.json";
import type { Res, Topic } from "./data";
import type { Badge, Repo, Tool } from "./extra";
import type { Step } from "./careers";
import type { Project } from "./projects";

export type Additions = {
  generatedAt: string | null;
  count: number;
  topics: Record<string, { free?: Res[]; paid?: Res[]; yt?: Res[] }>;
  repos: Record<string, Repo[]>;
  badges: Record<string, Badge[]>;
  tools: Record<string, Tool[]>;
  glossary: [string, string][];
  steps: Record<string, Step[]>;
  projects: Project[];
};

export const ADDITIONS = raw as unknown as Additions;

const norm = (u: string) => u.trim().replace(/^https?:\/\/(www\.)?/, "").replace(/\/+$/, "").toLowerCase();

/** Append items whose key is not already present. Base order is preserved. */
export function appendUnique<T>(base: T[], add: T[] | undefined, key: (x: T) => string): T[] {
  if (!add?.length) return base;
  const seen = new Set(base.map((x) => norm(key(x))));
  const out = [...base];
  for (const x of add) {
    const k = norm(key(x));
    if (!seen.has(k)) { seen.add(k); out.push(x); }
  }
  return out;
}

export function mergeRecord<T>(base: Record<string, T[]>, add: Record<string, T[]>, key: (x: T) => string): Record<string, T[]> {
  const out: Record<string, T[]> = { ...base };
  for (const [id, items] of Object.entries(add)) out[id] = appendUnique(out[id] ?? [], items, key);
  return out;
}

export function withAgentTopics(topics: Topic[]): Topic[] {
  return topics.map((t) => {
    const a = ADDITIONS.topics[t.id];
    if (!a) return t;
    return {
      ...t,
      free: appendUnique(t.free, a.free, (r) => r[1]),
      paid: appendUnique(t.paid, a.paid, (r) => r[1]),
      yt: appendUnique(t.yt, a.yt, (r) => r[1]),
    };
  });
}
